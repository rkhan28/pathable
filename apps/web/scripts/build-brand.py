"""Generate PathAble brand SVGs.

The wordmark is outlined from Atkinson Hyperlegible Next Bold so it renders
identically without the font installed. Run with:

    uv run scripts/build-brand.py
"""

from __future__ import annotations

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "src/app/fonts/atkinson-hyperlegible-next-latin-700-normal.woff2"
OUT = ROOT / "public/brand"

INK = "#0D1411"
FOREST = "#0F3D2E"
SIGNAL = "#13A06B"
WHITE = "#FFFFFF"

# One continuous stroke: open origin ring at the foot of the stem, up the stem,
# around the bowl, ending in the destination dot where the bowl meets the stem.
MARK_PATH = "M10 22.6V11a7 7 0 0 1 7-7a7 7 0 0 1 0 14h-2.4"
RING = (10, 26.2, 2.9)
DOT = (13.4, 18, 3.1)


def mark(stroke: str, ring: str, dot: str, *, size: int = 32, title: str = "PathAble") -> str:
    cx, cy, r = RING
    dx, dy, dr = DOT
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="{size}" height="{size}"'
        f' role="img" aria-label="{title}">'
        f'<path d="{MARK_PATH}" fill="none" stroke="{stroke}" stroke-width="3.2"'
        ' stroke-linecap="round" stroke-linejoin="round"/>'
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{ring}" stroke-width="2.4"/>'
        f'<circle cx="{dx}" cy="{dy}" r="{dr}" fill="{dot}"/>'
        "</svg>\n"
    )


def outline(text: str, tracking_em: float) -> tuple[str, float, float, float]:
    """Return (path d, width, ascender, descender) in font units, y flipped."""
    font = TTFont(FONT)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    ascender = font["hhea"].ascent
    descender = font["hhea"].descent
    kern = {}
    pen = SVGPathPen(glyph_set)
    x = 0.0
    names = [cmap[ord(ch)] for ch in text]
    for i, name in enumerate(names):
        tpen = TransformPen(pen, (1, 0, 0, -1, x, ascender))
        glyph_set[name].draw(tpen)
        advance = hmtx[name][0] + tracking_em * upm
        if i + 1 < len(names):
            advance += kern.get((name, names[i + 1]), 0)
        x += advance
    return pen.getCommands(), x - tracking_em * upm, ascender, descender


def wordmark(colour: str, mark_colours: tuple[str, str, str]) -> str:
    d, width, ascender, descender = outline("PathAble", tracking_em=-0.02)
    height = ascender - descender
    scale = 24 / height  # 24 px tall text box
    text_w = width * scale
    gap = 10
    total_w = 32 + gap + text_w
    stroke, ring, dot = mark_colours
    inner = mark(stroke, ring, dot).split(">", 1)[1].rsplit("</svg>", 1)[0]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.1f} 32"'
        f' height="32" role="img" aria-label="PathAble">'
        f"<g>{inner}</g>"
        f'<g transform="translate({32 + gap} 4) scale({scale:.5f})" fill="{colour}">'
        f'<path d="{d}"/></g></svg>\n'
    )


def app_icon() -> str:
    cx, cy, r = RING
    dx, dy, dr = DOT
    domes = "".join(
        f'<circle cx="{x}" cy="{y}" r="1.1" fill="#FFFFFF" fill-opacity="0.07"/>'
        for x in range(4, 32, 4)
        for y in range(4, 32, 4)
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="512" height="512"'
        ' role="img" aria-label="PathAble">'
        f'<rect width="32" height="32" rx="7" fill="{FOREST}"/>{domes}'
        '<g transform="translate(3.2 2.6) scale(0.8)">'
        f'<path d="{MARK_PATH}" fill="none" stroke="{WHITE}" stroke-width="3.4"'
        ' stroke-linecap="round" stroke-linejoin="round"/>'
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{WHITE}" stroke-width="2.6"/>'
        f'<circle cx="{dx}" cy="{dy}" r="{dr}" fill="#2BC48A"/></g></svg>\n'
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "pathable-mark.svg").write_text(mark(FOREST, FOREST, SIGNAL))
    (OUT / "pathable-mark-inverse.svg").write_text(mark(WHITE, WHITE, "#2BC48A"))
    (OUT / "pathable-wordmark.svg").write_text(wordmark(INK, (FOREST, FOREST, SIGNAL)))
    (OUT / "pathable-wordmark-inverse.svg").write_text(wordmark(WHITE, (WHITE, WHITE, "#2BC48A")))
    (OUT / "pathable-app-icon.svg").write_text(app_icon())
    d, width, ascender, descender = outline("PathAble", tracking_em=-0.02)
    (ROOT / "src/components/brand/wordmark-path.ts").write_text(
        "// Generated by scripts/build-brand.py from Atkinson Hyperlegible Next Bold.\n"
        f"export const WORDMARK_PATH = {d!r};\n"
        f"export const WORDMARK_WIDTH = {width:.1f};\n"
        f"export const WORDMARK_HEIGHT = {ascender - descender};\n"
    )
    print("wrote", sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
